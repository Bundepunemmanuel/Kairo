// ─── Hacker News + Bluesky fetching ─────────────────────────────────────
// Replaces Reddit entirely in this flow — see README-reddit-legacy.md for
// why (Reddit retired RSS outright; its OAuth API is realistically
// closed to this use case) and what the old dual-path/quota-tracking
// architecture looked like. Both calls take the same input
// (analysis.problemKeywords, generated by analyze.js as literal search
// phrases) and return posts already normalized into Kairo's standard
// shape — nothing downstream (scoring, display) needs to know or care
// which source a given post came from beyond that shape.
async function fetchHackerNews(problemKeywords) {
  try {
    const res = await fetch('/api/hackernews', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ problemKeywords }),
      signal: AbortSignal.timeout(15000),
    })
    if (!res.ok) return []
    const data = await res.json()
    return Array.isArray(data.posts) ? data.posts : []
  } catch (e) {
    console.log('[onboarding] hackernews fetch error:', e.message)
    return []
  }
}

async function fetchBluesky(problemKeywords) {
  try {
    const res = await fetch('/api/bluesky', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ problemKeywords }),
      signal: AbortSignal.timeout(15000),
    })
    if (!res.ok) return []
    const data = await res.json()
    return Array.isArray(data.posts) ? data.posts : []
  } catch (e) {
    console.log('[onboarding] bluesky fetch error:', e.message)
    return []
  }
}

// Runs both sources concurrently (independent APIs, nothing to share or
// pace against each other the way Reddit's split-IP quota once required)
// and merges into one list. Neither source failing takes down the other
// — same "the rest proceeds with whatever came back" principle the old
// Reddit dual-path fetch used.
async function fetchAllSources(problemKeywords) {
  const [hnPosts, blueskyPosts] = await Promise.all([
    fetchHackerNews(problemKeywords),
    fetchBluesky(problemKeywords),
  ])
  console.log(`[onboarding] hackernews ${hnPosts.length} posts, bluesky ${blueskyPosts.length} posts`)
  return [...hnPosts, ...blueskyPosts]
}

